"""The expected results of the app's port of the graph routines (app/src/main/java/com/onpath/app/suggest/NetSearch.kt)
on a small fixed network, computed by the POC's own code (net.py, generate.assemble / cut_spurs).

    python3 tools/suggest-poc/port_parity.py > app/src/test/resources/suggest/net-parity.txt

NetSearchParityTest reads the file and must get the same numbers. Run it again whenever net.py or the loop assembly
changes (the network is generated from a fixed seed, nothing here depends on map data).
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import generate  # noqa: E402
import net as netmod  # noqa: E402

rnd = random.Random(20261115)


def build():
    """A jittered 9 × 8 grid of ways with a few diagonals, a parallel way, a spur and a small island."""
    text = ["S 0"]
    nodes = []
    for y in range(8):
        for x in range(9):
            lon = 6.9 + x * 0.002 + rnd.randint(-300, 300) / 1e6
            lat = 51.1 + y * 0.0013 + rnd.randint(-200, 200) / 1e6
            nodes.append((round(lon, 6), round(lat, 6), float(rnd.randint(40, 160))))
    # the island: three nodes off to the east, joined to the grid only by a closed way
    for k in range(3):
        nodes.append((round(6.93 + k * 0.001, 6), 51.1, 75.0 + k))
    nodes[5] = (nodes[5][0], nodes[5][1], -8192.0)  # a node without height
    for i, (lon, lat, ele) in enumerate(nodes):
        text.append("N %d %r %r %r" % (i, lon, lat, ele))
    edges = []

    def add(a, b):
        m = netmod.dist(nodes[a][:2], nodes[b][:2])
        edges.append((a, b, round(m * 2) / 2.0))
    for y in range(8):
        for x in range(9):
            i = y * 9 + x
            if x < 8 and rnd.random() < 0.9:
                add(i, i + 1)
            if y < 7 and rnd.random() < 0.9:
                add(i, i + 9)
            if x < 8 and y < 7 and rnd.random() < 0.15:
                add(i, i + 10)
    add(10, 11)  # a parallel way
    add(72, 73)
    add(73, 74)
    add(8, 72)  # the island's only link to the grid (closed below)
    text.append("T 0 highway=path")
    for a, b, m in edges:
        text.append("E %d %d %r 1.0 1.0 0" % (a, b, m))
    return netmod.Net("\n".join(text))


def fmt(xs):
    return " ".join(repr(float(x)) if isinstance(x, float) else str(x) for x in xs)


def main():
    net = build()
    out = ["# generated by tools/suggest-poc/port_parity.py – do not edit; NetSearchParityTest"]
    for i, (lon, lat, ele) in enumerate(net.nodes):
        out.append("N %r %r %r" % (lon, lat, ele))
    for a, b, m, *_ in net.edges:
        out.append("E %d %d %r" % (a, b, m))
    island = len(net.edges) - 1
    cost = []
    for ei, e in enumerate(net.edges):
        f = rnd.choice([1.0, 1.25, 1.5, 2.0, 3.0])
        cost.append(-1.0 if ei == island or rnd.random() < 0.04 else e[2] * f)
    out.append("C " + fmt(cost))
    pen = {ei: rnd.choice([6.0, 2.5, 0.3]) for ei in rnd.sample(range(len(net.edges)), 25)}
    out.append("P " + " ".join("%d %r" % (k, v) for k, v in sorted(pen.items())))

    def result(head, r):
        d, prev, pe, ln = r
        out.append(head)
        out.append("D " + fmt(d))
        out.append("PREV " + fmt(prev))
        out.append("PE " + fmt(pe))
        out.append("LN " + fmt(ln))

    n = len(net.nodes)
    result("FULL 0", netmod.dijkstra(net, 0, cost))
    result("FULL 40", netmod.dijkstra(net, 40, cost))
    for src, stop, use_pen in [(0, 71, 0), (0, 71, 1), (36, 3, 1), (70, 8, 0), (12, 12, 0), (0, 73, 0)]:
        r = netmod.dijkstra(net, src, cost, pen if use_pen else None, stop=stop)
        result("STOP %d %d %d" % (src, stop, use_pen), r)
        out.append("PATH " + fmt(netmod.path(r[1], r[2], stop)))
    for src, max_len, use_pen in [(0, 500.0, 0), (40, 350.0, 1), (66, 1200.0, 0)]:
        result("BOUND %d %r %d" % (src, max_len, use_pen), netmod.dijkstra(net, src, cost, pen if use_pen else None,
                                                                             max_len=max_len))
    for start in (0, 73):
        ok = [c >= 0 for c in cost]
        net.start = start
        moved = netmod.seat_start(net, ok)
        out.append("SEAT %d %s" % (start, "".join("1" if o else "0" for o in ok)))
        out.append("R %d %d" % (net.start, moved))
    for walk in ([0, 1, 2, 11, 20, 29], [5, 6, 15, 24, 33, 42, 51, 60], list(range(18, 27))):
        out.append("CLIMB " + fmt(walk))
        out.append("R %r" % netmod.climb(net, walk))

    # the loop assembly as generate.pool calls it: the full search from the start, used ×6, beside ×2.5, free stem
    class F:
        ln = [e[2] for e in net.edges]

    class Ch:
        family = {"free_stem_m": 300.0}

    class P:
        pass
    net.start = 0
    P.net, P.F, P.ch, P.cost = net, F, Ch, cost
    d0, P.prev0, P.pe0, _ = netmod.dijkstra(net, 0, cost)
    S = {"search": {"used": 6.0, "beside_used": 2.5}}
    for pts in ([70], [8, 71], [62, 44], [26, 71, 63], [40], [73]):
        out.append("ASM " + fmt(pts))
        r = generate.assemble(P, S, pts)
        out.append("R " + ("none" if r is None else fmt(r)))
    for k in range(8):  # random walks from the start: going back the same way now and then, meeting itself
        es, node = [], 0
        for _ in range(10 + 3 * k):
            if es and rnd.random() < 0.2:
                ei = es[-1]
            else:
                ei = rnd.choice(net.adj[node])[1]
            es.append(ei)
            node = net.other(ei, node)
        out.append("CUT " + fmt(es))
        out.append("R " + fmt(generate.cut_spurs(net, F, es)))
    print("\n".join(out))


if __name__ == "__main__":
    main()
