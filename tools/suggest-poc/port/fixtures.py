def pysets():
    rnd = random.Random(20261116)
    out = []
    for k in range(60):
        hi = rnd.choice([20, 200, 5000, 300000])
        a = set()
        ops = []
        for _ in range(rnd.randint(1, 120)):
            x = rnd.randrange(hi)
            a.add(x)
            ops.append("a%d" % x)
            if rnd.random() < 0.08 and a:
                y = rnd.choice(sorted(a))
                a.discard(y)
                ops.append("r%d" % y)
        if k % 3 == 0:  # a union into a fresh set and into a filled one (Index.at)
            seq = [rnd.randrange(hi) for _ in range(rnd.randint(0, 30))]
            b = set()
            for x in seq:
                b.add(x)
            u = set()
            u |= b
            ops.append("u" + ",".join(str(x) for x in seq))  # b's adds, then u |= b (fresh), then u |= a (filled)
            u |= a
            out.append("UNION " + " ".join(ops))
            out.append("R " + " ".join(map(str, u)))
        else:
            out.append("OPS " + " ".join(ops))
            out.append("R " + " ".join(map(str, a)))
    return out


