#!/usr/bin/env python3
"""A plain-JVM stand-in for the :strings module (com.onpath.strings.Res / Txt + Compose's StringResource) for the
tour-suggestion core on the desktop (kt.sh): the texts of strings_suggest.xml in one language – German by default, the
POC's language, so the port's card titles and notes compare word for word. Placeholders as the app's Txt formats them
(`%N$s` / `%N$d` → the N-th argument, nothing else touched: "12 % doppelt" stays as it is).
Usage: strings_stub.py <repoRoot> <out.kt> [de|en]"""
import html
import re
import sys

root, out = sys.argv[1], sys.argv[2]
lang = sys.argv[3] if len(sys.argv) > 3 else "de"
base = root + "/strings/src/commonMain/composeResources/"


def read(folder):
    try:
        x = open(base + folder + "/strings_suggest.xml", encoding="utf-8").read()
    except OSError:
        return {}
    return {m.group(1): html.unescape(m.group(2)).replace("\\'", "'").replace('\\"', '"')
            for m in re.finditer(r'<string name="([a-z0-9_]+)"[^>]*>(.*?)</string>', x, re.S)}


texts = read("values")
if lang != "en":
    texts.update(read("values-" + lang))


def kt(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


with open(out, "w", encoding="utf-8") as o:
    o.write("// generated by tools/suggest-poc/port/strings_stub.py – do not edit\n")
    o.write("package org.jetbrains.compose.resources\nclass StringResource(val key: String, val text: String)\n")
with open(out.replace(".kt", "Res.kt"), "w", encoding="utf-8") as o:
    o.write("// generated by tools/suggest-poc/port/strings_stub.py – do not edit\npackage com.onpath.strings\n")
    o.write("import org.jetbrains.compose.resources.StringResource\n")
    o.write("object Res { object string }\n")
    for n in sorted(texts):
        o.write("val Res.string.%s: StringResource get() = StringResource(%s, %s)\n" % (n, kt(n), kt(texts[n])))
    o.write('''object Txt {
    fun language(): String = %s
    fun s(res: StringResource, vararg args: Any): String {
        val raw = res.text
        val b = StringBuilder()
        var i = 0
        while (i < raw.length) {
            val c = raw[i]
            if (c == '%%' && i + 3 < raw.length && raw[i + 1].isDigit() && raw[i + 2] == '$' && (raw[i + 3] == 's' || raw[i + 3] == 'd')) {
                b.append(args[raw[i + 1] - '1'].toString()); i += 4
            } else { b.append(c); i++ }
        }
        return b.toString()
    }
}
''' % kt(lang))
print(len(texts), "strings", lang)
